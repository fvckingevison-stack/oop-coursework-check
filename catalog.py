GENDER_CODES = {"Ч": "Чоловіче", "Ж": "Жіноче", "У": "Унісекс"}


def make_catalog_items(colors_per_model=2, existing=()) -> list:
    have = {(i.category, i.name, i.gender) for i in existing}
    items = []
    for cat, name, season, tmin, tmax, genders in CATALOG:
        for code in genders:
            if (cat, name, GENDER_CODES[code]) in have:
                continue
            for color in random.sample(COLORS, colors_per_model):
                items.append(create_item(cat, f"item_{uuid.uuid4().hex[:6]}", name, color, season,
                                         tmin, tmax, "", GENDER_CODES[code]))
    return items